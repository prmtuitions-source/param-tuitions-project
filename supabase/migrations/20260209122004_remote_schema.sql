CREATE OR REPLACE FUNCTION public.match_teachers(p_parent_lat double precision, p_parent_long double precision, p_gender text DEFAULT NULL::text, p_board text DEFAULT NULL::text, p_min_experience integer DEFAULT 0, p_min_marks integer DEFAULT 0, p_radius_km double precision DEFAULT 5, p_time_slot text DEFAULT NULL::text)
 RETURNS TABLE(id uuid, full_name text, phone_number text, photo_url text, gender text, experience_years integer, class_10_marks integer, dist_meters double precision)
 LANGUAGE plpgsql
AS $function$
BEGIN
  RETURN QUERY
  SELECT
    p.id,
    p.full_name,
    p.phone_number,
    td.photo_url,
    td.gender,
    td.experience_years,
    td.class_10_marks,
    (st_distance(
      st_point(td.longitude, td.latitude)::geography,
      st_point(p_parent_long, p_parent_lat)::geography
    )) as dist_meters
  FROM profiles p
  JOIN teacher_details td ON p.id = td.id
  WHERE p.user_role = 'teacher'
  AND (p_gender IS NULL OR td.gender = p_gender)
  AND (p_board IS NULL OR td.preferred_boards ILIKE '%' || p_board || '%')
  AND (td.experience_years >= p_min_experience)
  AND (td.class_10_marks >= p_min_marks)
  AND (
      st_distance(
        st_point(td.longitude, td.latitude)::geography,
        st_point(p_parent_long, p_parent_lat)::geography
      ) <= (p_radius_km * 1000)
  )
  AND (
    p_time_slot IS NULL 
    OR EXISTS (
      SELECT 1 FROM teacher_availability ta 
      WHERE ta.teacher_id = p.id 
      -- Basic check: If the teacher has ANY availability set, they show up.
    )
  )
  ORDER BY dist_meters ASC;
END;
$function$
;

CREATE OR REPLACE FUNCTION public.match_teachers(p_parent_lat double precision, p_parent_long double precision, p_gender text DEFAULT NULL::text, p_board text DEFAULT NULL::text, p_min_marks integer DEFAULT 0)
 RETURNS TABLE(id uuid, full_name text, gender text, experience_years integer, class_10_marks integer, dist_meters double precision)
 LANGUAGE plpgsql
AS $function$
BEGIN
  RETURN QUERY
  SELECT 
    p.id, 
    p.full_name, 
    p.gender,
    td.experience_years,
    td.class_10_marks,
    ST_Distance(p.location, ST_SetSRID(ST_MakePoint(p_parent_long, p_parent_lat), 4326)::geography) AS dist_meters
  FROM profiles p
  JOIN teacher_details td ON p.id = td.id
  WHERE 
    p.user_role = 'teacher'
    AND ST_DWithin(p.location, ST_SetSRID(ST_MakePoint(p_parent_long, p_parent_lat), 4326)::geography, 5000) -- 5KM LIMIT
    AND (p_gender IS NULL OR p.gender = p_gender)
    AND (p_board IS NULL OR td.background_board = p_board)
    AND td.class_10_marks >= p_min_marks
  ORDER BY dist_meters ASC;
END;
$function$
;

