CREATE OR REPLACE FUNCTION public.broadcast_new_lead(p_tuition_id uuid)
 RETURNS void
 LANGUAGE plpgsql
AS $function$
DECLARE
    t_lat DOUBLE PRECISION;
    t_long DOUBLE PRECISION;
BEGIN
    -- Get the coordinates of the new inquiry
    SELECT latitude, longitude INTO t_lat, t_long FROM tuitions WHERE id = p_tuition_id;

    -- Insert notifications for teachers within 5km who are Grade A or A+
    INSERT INTO notifications (profile_id, title, message, type)
    SELECT 
        tr.id, 
        'New Tuition Near You!', 
        'A new ' || t.subject || ' inquiry is available within 5km.',
        'new_lead'
    FROM teacher_rankings tr
    JOIN tuitions t ON t.id = p_tuition_id
    JOIN teacher_performance_scores tps ON tr.id = tps.id
    WHERE (point(tr.longitude, tr.latitude) <@> point(t_long, t_lat)) * 1.60934 <= 5
    AND tps.tutor_grade IN ('A', 'A+');
END;
$function$
;

