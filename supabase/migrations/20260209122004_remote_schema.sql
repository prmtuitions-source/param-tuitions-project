CREATE OR REPLACE FUNCTION public.get_next_admin_tn(p_admin_zone text)
 RETURNS text
 LANGUAGE plpgsql
AS $function$
DECLARE
    next_val INTEGER;
    counter_key TEXT;
    block_limit INTEGER;
BEGIN
    -- Determine which counter and limit to use
    IF p_admin_zone = 'Admin 1' THEN
        counter_key := 'admin_1_next_tn';
    ELSE
        counter_key := 'admin_2_next_tn';
    END IF;

    -- Fetch current value
    SELECT value::int INTO next_val FROM system_settings WHERE key = counter_key FOR UPDATE;
    
    -- Check if they are at the end of their 1000 block (e.g., 3000, 4000, etc.)
    -- A simple check: if the next number ends in '001' of the next thousand
    IF (next_val % 1000) = 0 THEN
        -- Log a notification for Super Admin that a block is finished
        INSERT INTO notifications (profile_id, title, message, type)
        SELECT id, 'Block Exhausted!', p_admin_zone || ' has finished their TN block at ' || next_val, 'system_alert'
        FROM profiles WHERE user_role = 'super_admin';
    END IF;

    -- Increment and return
    UPDATE system_settings 
    SET value = (next_val + 1)::text 
    WHERE key = counter_key;

    RETURN 'TN' || next_val::text;
END;
$function$
;

