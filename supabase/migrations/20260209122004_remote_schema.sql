CREATE OR REPLACE FUNCTION public.match_teachers(p_parent_lat double precision, p_parent_long double precision, p_gender text DEFAULT NULL::text, p_board text DEFAULT NULL::text, p_min_experience integer DEFAULT 0, p_min_marks integer DEFAULT 0)
 RETURNS TABLE(id uuid, full_name text, gender text, experience_years integer, class_10_marks integer, dist_meters double precision)
 LANGUAGE plpgsql
AS $function$
BEGIN
  RETURN QUERY
  SELECT 
    p.id, 
    p.full_name, 
    p.gender,
    td.experience_years,
    td.class_10_marks,
    ST_Distance(p.location, ST_SetSRID(ST_MakePoint(p_parent_long, p_parent_lat), 4326)::geography) AS dist_meters
  FROM profiles p
  JOIN teacher_details td ON p.id = td.id
  WHERE 
    p.user_role = 'teacher'
    AND ST_DWithin(p.location, ST_SetSRID(ST_MakePoint(p_parent_long, p_parent_lat), 4326)::geography, 5000) -- 5km Radius
    AND (p_gender IS NULL OR p.gender = p_gender)
    AND (p_board IS NULL OR td.background_board = p_board)
    AND td.experience_years >= p_min_experience
    AND td.class_10_marks >= p_min_marks
  ORDER BY dist_meters ASC;
END;
$function$
